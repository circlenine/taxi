# 表記ゆれの検査（読みでまとめる方式。10/8 ご指摘「本当に全部の表記ゆれを見ているのか」）
# 文を言葉に分け（janome）、同じ読みなのに書き方がちがう言葉を全部さがす。
# 前もって決めた言葉の組み合わせだけを調べる方法では、「器材／機材」を見落とした。
# この方法なら、組み合わせを知らなくても見つかる。
# 下の OK は、読みが同じでも別の言葉なので問題ないもの（例：「か」と「可」）。新しく出たら、目で見て判断して足す。
import re, sys
from collections import defaultdict
from janome.tokenizer import Tokenizer
OK = {
 "カ": {"か", "可"}, "タ": {"た", "他"}, "テ": {"て", "手"}, "デ": {"で", "出"},
 "ナッ": {"なっ", "鳴っ"}, "ヒク": {"引く", "低"}, "ヨウ": {"よう", "用"},
 "ツケ": {"付け", "着け"},
 "イキ": {"息", "行き"}, "キ": {"き", "着", "気", "来", "器"}, "ヘン": {"編", "変"},   # 気をつける／来ていない、器材準備編／変な文 は別の言葉
 "カイ": {"会", "回", "買い"}, "スウ": {"吸う", "数"},
 "ハイ": {"肺", "吐い"}, "キュウ": {"急", "給"},   # 10/22 「オーラル給気」（インストラクターさんの言葉）と「急に」は別の言葉
 "マッ": {"まっ", "待っ"},
 # 10/23 3冊をまとめて調べたときに出た、読みが同じでも別の言葉（目で見て確かめた）：着る／切る、締まっ／〜してしまった、留める（バックル）／止める、
 #   早い（時間）／速い（流れ）、間（あいだ）／停まる の「ま」（どちらも言葉の分け方のずれ）
 "キル": {"着る", "切る"}, "コウ": {"高", "こう"},   # 高すぎ（言葉の分け方のずれ）／こうすると
 "シマッ": {"締まっ", "しまっ"}, "トメ": {"留め", "止め"}, "ハヤイ": {"早い", "速い"}, "マ": {"間", "ま"},
 # 10/22 1スキル＝1ページで出た、読みが同じでも別の言葉（目で見て確かめた）：伝え合う／会う、ふり返る／切りかえる、肩／方法、線／3選、
 #   慣れ／鳴れ、まわり（周り）／半回り。「曳航（えいこう）」は読みを添えたもの
 "アウ": {"合う", "会う"}, "カエル": {"返る", "変える"}, "カタ": {"方", "肩"}, "セン": {"選", "線"}, "ナレ": {"鳴れ", "慣れ"},
 "マワリ": {"まわり", "回り"}, "バ": {"ば", "場"},   # 10/22 「なければ」と「その場」 "エイコウ": {"曳航", "えいこう"},   # 10/20 「停まって」の「まっ」と「待って」は別の言葉
 "イレ": {"いれ", "入れ"}, "ミセ": {"店", "見せ"}, "メ": {"め", "目"}, "マイ": {"枚", "舞い"}, "ハナシ": {"話", "話し", "離し"}, "イル": {"いる", "要る"}, "ミ": {"見", "身"}, "オク": {"おく", "奥"}, "カエリ": {"返り", "帰り"}, "シタ": {"下", "舌"}, "ホウ": {"法", "ほう"},   # 10/19 スキル編：肺と「吐いて」、1枚と「砂が舞い」、「動画にない話」と「話しておく」は別の言葉   # 息と「行きわたる」、委員会と「回す」は別の言葉   # 10/19 耳抜き3選：「舌の奥」「〇〇法」、「帰り道」と「ふり返り」、「要る」も別の言葉
}
# 書き方を変えてはいけない固有の名前（動画の題名など）。ここに入っている文字列は、調べる前に取りのぞく
PROPER = ["ダイビング機材セッティング", "こんな時"]   # 10/22 「こんな時」は、まーく様の決めた札の名前（各ページの頭）。本文は「とき」にそろえる   # 動画の正式な題名なので「機材」のまま
# 10/23 まーく様「指摘する以外の表記ゆれがないか、全て確認できているのか」→ 3冊をまとめて調べられるように（ファイルを何個でも渡せる）
h = "".join(open(f).read() for f in sys.argv[1:])
h = re.sub(r'<rt>.*?</rt>|<span class="rt">[^<]*</span>', '', h)   # 10/20 ルビ（ふりがな）は、点検では数えない
body = "".join(x.split("</head>",1)[-1] for x in h.split("<!doctype html>"))
body = re.sub(r"<script.*?</script>|<svg.*?</svg>|<style.*?</style>", "", body, flags=re.S)
body = re.sub(r'<div class="umsg">.*?</div>', "", body, flags=re.S)
body = re.sub(r'<div class="umsg2">.*?</div></div></div>', "", body, flags=re.S)   # 10/22 組み直した形   # 10/22 まーく様ご自身の言葉（まとめの下）は、書き方をそろえる対象にしない
t = re.sub(r"&[a-z#0-9]+;", "", re.sub(r"<[^>]+>", "\n", body))
for p in PROPER: t = t.replace(p, "")
# 左上の「更新日時：2026/10/15(木)」は言葉ではない。曜日の1字（木・火など）が「き」「か」とぶつかって、
# 木曜・火曜にだけ落ちていた（10/15 見つけた）。日付ごと取りのぞいてから調べる。
t = re.sub(r"更新日時：\d{4}/\d{2}/\d{2}\([月火水木金土日]\)", "", t)
t = t.replace("試してみてね", "").replace("タップしてみてね", "")   # 10/23 まーく様の言葉（「〜してみる」の「みる」は、ひらがなが正しい書き方）
t = t.replace("よーくスクリュー", "")   # 10/23 まーく様のだじゃれ（ヨークスクリューにかけて、わざと ひらがな）
t = t.replace("これで、あいちゃん", "")   # 10/24 まーく様「コレで、は日本語的におかしいので、これで、に」（ほかの「コレ」は札の言い回しのまま）
tk = Tokenizer(); by = defaultdict(lambda: defaultdict(int))
for line in t.split("\n"):
    line = line.strip()
    if not line: continue
    pos = 0
    for x in tk.tokenize(line):
        a = pos; pos += len(x.surface)
        if x.part_of_speech.startswith("記号"): continue
        r = x.reading if x.reading != "*" else x.surface
        # 「水につける（浸ける）」は「付ける」と別の言葉。前に「水に」「バケツに」がある「つけ」は、別に数える（10/13）
        if x.surface == "つけ" and re.search(r"(水|バケツ)に[^。！]{0,4}$", line[:a]): r = "ツケ（浸）"
        by[r][x.surface] += 1
bad = [f"NG 表記ゆれ（読み {r}）… " + "／".join(f"{k}×{v}" for k, v in d.items())
       for r, d in sorted(by.items()) if len(d) > 1 and not set(d) <= OK.get(r, set())]
print("\n".join(bad) if bad else f"表記ゆれ（読みでまとめる検査）OK（{len(by)}語）")
sys.exit(1 if bad else 0)
